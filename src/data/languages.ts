// Fallback for remaining languages to provide authentic localized strings
export function getTranslation(langCode: string = 'hi', key: keyof TranslationDictionary): string {
  const dict = TRANSLATIONS[langCode] || TRANSLATIONS['hi'] || TRANSLATIONS['en'];
  if (dict && dict[key]) {
    return dict[key];
  }
  const fallback = TRANSLATIONS['hi']?.[key] || TRANSLATIONS['en']?.[key] || (key as string);
  return fallback;
}

// Format local date with locale support
export function formatLocalDate(date: Date, langCode: string = 'hi'): string {
  try {
    const localeMap: Record<string, string> = {
      hi: 'hi-IN',
      en: 'en-IN',
      bn: 'bn-IN',
      te: 'te-IN',
      mr: 'mr-IN',
      ta: 'ta-IN',
      ur: 'ur-IN',
      gu: 'gu-IN',
      kn: 'kn-IN',
      ml: 'ml-IN',
      or: 'or-IN',
      pa: 'pa-IN',
      as: 'as-IN',
      mai: 'hi-IN',
      sat: 'sat-IN',
      ks: 'ks-IN',
      ne: 'ne-NP',
      gom: 'gom-IN',
      sd: 'sd-IN',
      doi: 'doi-IN',
      mni: 'mni-IN',
      brx: 'brx-IN',
      sa: 'sa-IN'
    };
    const targetLocale = localeMap[langCode] || 'hi-IN';
    return date.toLocaleDateString(targetLocale, {
      weekday: 'long',
      day: 'numeric',
      month: 'long',
      year: 'numeric'
    });
  } catch (e) {
    return date.toLocaleDateString('hi-IN');
  }
}

// Get period of the day label
export function getDayPeriodLabel(hours: number, langCode: string = 'hi'): { key: keyof TranslationDictionary; label: string } {
  let key: keyof TranslationDictionary = 'greetingMorning';
  if (hours >= 12 && hours < 16) key = 'greetingAfternoon';
  else if (hours >= 16 && hours < 20) key = 'greetingEvening';
  else if (hours >= 20 || hours < 5) key = 'greetingNight';
  
  return {
    key,
    label: getTranslation(langCode, key)
  };
}
